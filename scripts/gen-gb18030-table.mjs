#!/usr/bin/env node
/**
 * Writes src/lib/encoder/gb18030-table.ts: the GB18030 two-byte index and the
 * four-byte BMP ranges, read out of this machine's own gb18030 decoder (Node's
 * built-in ICU). Offline: nothing is downloaded. Run it again only if the
 * table has to follow a newer edition of the standard; the test
 * src/lib/encoder/gb18030.test.ts checks the codec against the platform.
 *
 *   node scripts/gen-gb18030-table.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/encoder/gb18030-table.ts");
const td = new TextDecoder("gb18030", { fatal: true });

function one(bytes) {
  const s = td.decode(Uint8Array.from(bytes));
  const cps = [...s].map((c) => c.codePointAt(0));
  if (cps.length !== 1) throw new Error(`not one code point: ${bytes}`);
  return cps[0];
}

// Two-byte index: pointer = (lead - 0x81) * 190 + trail offset.
const TWO = 23940;
const two = [];
for (let p = 0; p < TWO; p++) {
  const lead = 0x81 + Math.floor(p / 190);
  const t = p % 190;
  two.push(one([lead, t < 0x3f ? t + 0x40 : t + 0x41]));
}

// Runs of consecutive code points, written as signed base-36 jumps.
const runs = [];
let expect = 0;
for (let p = 0; p < TWO;) {
  let n = 1;
  while (p + n < TWO && two[p + n] === two[p] + n) n++;
  const jump = two[p] - expect;
  runs.push(
    (jump < 0 ? "-" : "") + Math.abs(jump).toString(36) + (n > 1 ? ":" + n.toString(36) : ""),
  );
  expect = two[p] + n;
  p += n;
}

// Four-byte BMP ranges, pointers 0..39419. Pointer 7457 is the one exception
// the standard writes out by itself (U+E7C7); it is kept out of the ranges.
const SPECIAL_POINTER = 7457;
function fourBytes(p) {
  let n = p;
  const b1 = 0x81 + Math.floor(n / 12600);
  n %= 12600;
  const b2 = 0x30 + Math.floor(n / 1260);
  n %= 1260;
  return [b1, b2, 0x81 + Math.floor(n / 10), 0x30 + (n % 10)];
}
const special = one(fourBytes(SPECIAL_POINTER));
const rp = [];
const rc = [];
let prev = -2;
for (let p = 0; p <= 39419; p++) {
  const cp = p === SPECIAL_POINTER ? prev + 1 : one(fourBytes(p));
  if (cp !== prev + 1) {
    rp.push(p);
    rc.push(cp);
  }
  prev = cp;
}
for (let i = 1; i < rc.length; i++) {
  if (rc[i] <= rc[i - 1]) throw new Error(`ranges not in code point order at ${rp[i]}`);
}

const hex = (n) => "0x" + n.toString(16);
const wrap = (items) => {
  const lines = [];
  let line = "";
  for (const it of items) {
    if (line.length + it.length + 2 > 96) {
      lines.push(line);
      line = "";
    }
    line += (line ? ", " : "") + it;
  }
  if (line) lines.push(line);
  return lines.map((l) => "  " + l + ",").join("\n");
};
const chunk = (s, w) => s.match(new RegExp(`.{1,${w}}`, "g"));

const src = `/**
 * GB18030 tables. GENERATED by scripts/gen-gb18030-table.mjs from the
 * platform's own gb18030 decoder (Node ${process.version}, ICU ${process.versions.icu}).
 * Do not edit by hand.
 *
 * TWO_BYTE_RUNS: the two-byte index, pointers 0..${TWO - 1} in order, as runs of
 * consecutive code points. Each run is a signed base-36 jump from where the
 * last run ended, then ":" and the run length in base 36 when longer than one.
 *
 * RANGES_POINTER / RANGES_CP: where each linear stretch of the four-byte BMP
 * area starts. Pointer ${SPECIAL_POINTER} maps alone to U+${special.toString(16).toUpperCase()}.
 */

export const TWO_BYTE_COUNT = ${TWO};

export const TWO_BYTE_RUNS =
${chunk(runs.join(","), 96)
  .map((c) => `  "${c}"`)
  .join(" +\n")};

export const RANGES_POINTER = [
${wrap(rp.map(String))}
];

export const RANGES_CP = [
${wrap(rc.map(hex))}
];

export const SPECIAL_POINTER = ${SPECIAL_POINTER};
export const SPECIAL_CP = ${hex(special)};
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: ${runs.length} runs, ${rp.length} ranges, ${src.length} chars`);
